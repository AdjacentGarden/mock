BOOK_IDS = ['catalog_high_school_math_required_2', 'catalog_advanced_mathematics_1']
EXTRA_TITLES = {'functions-1':'函数图像与性质','functions-2':'导数与单调性','functions-3':'导数的综合应用'}

def render_topic(chapter, item):
    concept = chapter.get('ai_title') or chapter.get('source_title') or chapter['chapter_id']
    terms = item['terms']
    definition_tag, rule_tag, example_tag, misconception_tag, transfer_tag = CONCEPT_TAGS[chapter['chapter_id']]
    assert len(terms) == 6, (chapter['chapter_id'], terms)
    content = [
        ('explanation', '概念与规律', item['definition'] + '\n\n' + item['rule'] + '\n\n核心关系：' + item['formula'] + '。\n\n' + item['comparison']),
        ('diagram', '把关系画出来', '图解主线：' + ' → '.join([terms[0], terms[2], terms[4]]) + '。核心关系为“' + item['formula'] + '”。\n\n' + item['worked'] + '\n\n' + item['transfer']),
        ('comparison', '区分相近概念与易错点', '需要辨别的说法：“' + item['misconception'] + '”\n\n' + item['correction'] + '\n\n' + item['comparison'] + '\n\n对照核心关系“' + item['formula'] + '”，把定义、条件与结果分别对应起来；本节算例的答案为“' + item['answer'] + '”。'),
        ('application', '例题推演与迁移', '原创算例：' + item['prompt'] + '\n\n' + item['worked'] + '\n\n结论：' + item['answer'] + '。\n\n' + item['transfer'] + '\n\n核对要点：' + item['correction']),
    ]
    extensions = {
        'explanation': '应用边界：' + item['transfer'],
        'diagram': '图示核对：' + item['correction'] + '\n' + item['comparison'],
        'comparison': '回到定义：' + item['definition'],
        'application': '所用规律：' + item['rule'] + '\n' + item['comparison'],
    }
    blocks = []
    for kind,title,text in content:
        if len(re.findall(r'[\u3400-\u9fff]',text)) < 100:
            text += '\n\n' + extensions[kind]
        assert len(re.findall(r'[\u3400-\u9fff]',text)) >= 100, (chapter['chapter_id'],kind)
        blocks.append(dict(block_type=kind,title=title,content=text))
    choices = [item['answer']] + item['distractors']
    assert len(set(choices)) == 4, (chapter['chapter_id'], choices)
    # Rotate the correct answer so all four button positions are exercised.
    offset = sum(map(ord,chapter['chapter_id'])) % 4
    choices = choices[offset:] + choices[:offset]
    return dict(chapter_id=chapter['chapter_id'], summary=item['definition'] + '\n' + item['rule'],
        objectives=[f'说明{terms[0]}与{terms[1]}的含义和适用条件', f'运用{terms[2]}与{terms[3]}完成本节算例', f'辨别{terms[4]}与{terms[5]}相关的常见误区'],
        key_concepts=terms, blocks=blocks,
        flashcards=[
            dict(front=f'{concept}：核心概念怎样表述？', back=item['definition'], concept=definition_tag),
            dict(front=f'{concept}：本节使用什么规律与公式？', back=item['rule']+'\n'+item['formula'], concept=rule_tag),
            dict(front='这道算例应怎样推理？\n'+item['prompt'], back=item['worked'], concept=example_tag),
            dict(front='快速回忆具体结果：'+item['prompt'], back=item['answer']+'。'+item['formula'], concept=example_tag),
            dict(front='下面说法错在哪里？\n'+item['misconception'], back=item['correction'], concept=misconception_tag),
            dict(front=f'怎样把{concept}的方法用于新情境？', back=item['comparison']+'\n'+item['transfer'], concept=transfer_tag),
        ],
        quizzes=[
            dict(question_type='judgment', prompt=item['misconception'], choices=['正确','错误'], answer='错误', explanation=item['correction'], concept=misconception_tag),
            dict(question_type='choice', prompt=item['prompt'], choices=choices, answer=item['answer'], explanation=item['worked'], concept=example_tag),
            dict(question_type='short-answer', prompt='请解答下面的原创算例，并说明所用关系与核验方法：\n'+item['prompt'], choices=[], answer=item['worked'], explanation=item['rule']+'\n'+item['transfer'], concept=example_tag),
        ], diagram_steps=[terms[0],terms[2],terms[4]], diagram_focus=item['formula'])

def main():
    sources=json.loads((ROOT/'Resources/Data/sources.json').read_text())
    directory=ROOT/'Resources/Data/MockBooks'
    directory.mkdir(parents=True,exist_ok=True)
    expected=set(EXTRA_TITLES)
    for book in sources:
        bid=book['summary']['book_id']
        if bid not in BOOK_IDS: continue
        parents={c.get('parent_id') for c in book['chapters'] if c.get('parent_id')}
        leaves=[c for c in book['chapters'] if c['chapter_id'] not in parents]
        expected.update(c['chapter_id'] for c in leaves)
        topics=[render_topic(c,SEEDS[c['chapter_id']]) for c in leaves]
        result=dict(book_id=bid,version=2,topics=topics)
        (directory/(bid+'.json')).write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
        print(f'{bid}: {len(topics)} lessons, {len(topics)*4} blocks, {len(topics)*6} flashcards, {len(topics)*3} questions')
    extras=[render_topic(dict(chapter_id=k,ai_title=v),SEEDS[k]) for k,v in EXTRA_TITLES.items()]
    (directory/'community_functions.json').write_text(json.dumps(dict(book_id='community_functions',version=2,topics=extras),ensure_ascii=False,indent=2)+'\n')
    assert set(CONCEPT_TAGS)==expected, ('missing concept labels',expected-set(CONCEPT_TAGS))
    assert set(SEEDS)==expected, ('missing',expected-set(SEEDS),'extra',set(SEEDS)-expected)
    print(f'community_functions: {len(extras)} lessons; all {len(SEEDS)} topic IDs and answer sets verified')

if __name__=='__main__':main()

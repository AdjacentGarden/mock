def fixture_topic(chapter):
    cid = chapter['chapter_id']
    data = BANK[cid]
    title = chapter.get('ai_title') or chapter['source_title']
    c = data['concepts']
    assert len(c) == 6 and len(set(c)) == 6, (cid, 'six distinct concepts required')
    steps = data['flow']
    assert len(steps) == 3 and all(len(s) <= 18 for s in steps), (cid, steps)
    assert len(data['focus']) <= 70, cid
    judgment, correct = data['judgment']
    choice, options, answer_index = data['choice']
    short, answer = data['short']
    blocks = [
        dict(block_type='explanation', title='理解' + c[0],
             content=data['definition'] + '\n\n' + data['rule'] + '\n\n' + data['mechanism']),
        dict(block_type='diagram', title='沿图解追踪' + c[0],
             content='关系图按“' + ' → '.join(steps) + '”展开。' + data['mechanism']
                     + '\n\n图中各箭头对应本节的具体关系：' + data['rule']),
        dict(block_type='comparison', title='辨析边界与易混关系',
             content=data['contrast'] + '\n\n' + data['caution']),
        dict(block_type='application', title='用具体例子检验结论',
             content=data['worked'] + '\n\n延伸解释：' + answer + '\n\n' + data['caution']),
    ]
    # The counts and four-part flow mirror the existing biology lessons.
    cards = [
        dict(front='本节的“' + c[0] + '”指什么？', back=data['definition'], concept=c[0]),
        dict(front='与“' + c[1] + '”相关的核心关系怎样表述？', back=data['rule'], concept=c[1]),
        dict(front='分析“' + title + '”时，如何顺着图解推理？', back=data['mechanism'], concept=c[2]),
        dict(front='本节例子中的已知量与结果是什么？', back=data['worked'], concept=c[3]),
        dict(front='学习本节时，哪两种说法最容易混淆？', back=data['contrast'], concept=c[4]),
        dict(front='把本节规律迁移到新问题前，需要检查什么？', back=data['caution'], concept=c[5]),
    ]
    quizzes = [
        dict(question_type='judgment', prompt=judgment, choices=['正确', '错误'],
             answer='正确' if correct else '错误', explanation=data['contrast'] + ' ' + data['rule'], concept=c[0]),
        dict(question_type='choice', prompt=choice, choices=options,
             answer=options[answer_index], explanation=data['rule'] + ' ' + data['worked'], concept=c[1]),
        dict(question_type='short-answer', prompt=short, choices=[], answer=answer,
             explanation=answer + ' 可对照本节的关系图与具体例子核对。', concept=c[2]),
    ]
    for block in blocks:
        assert len(re.findall(r'[\u4e00-\u9fff]', block['content'])) >= 100, (cid, block['block_type'], '100 Chinese characters required')
    assert len({q['prompt'] for q in quizzes}) == 3, cid
    return dict(chapter_id=cid, summary=data['definition'],
                objectives=[f'说明{c[0]}与{c[1]}的含义和关系',
                            f'运用{c[2]}和{c[3]}解释本节的具体例子',
                            f'区分{c[4]}与{c[5]}相关问题的条件和边界'],
                key_concepts=c, blocks=blocks, flashcards=cards, quizzes=quizzes,
                diagram_steps=steps, diagram_focus=data['focus'])


def main():
    originals = json.loads((ROOT / 'Resources/Data/sources.json').read_text())
    extra = ROOT / 'Resources/Data/MockBooks/extra-sources.json'
    if extra.exists():
        originals += json.loads(extra.read_text())
    sources = {b['summary']['book_id']: b for b in originals}
    target = ROOT / 'Resources/Data/MockBooks'
    target.mkdir(parents=True, exist_ok=True)
    used = set()
    for book_id in BOOKS:
        assert book_id in sources, 'Missing directory for ' + book_id
        source = sources[book_id]
        parents = {c.get('parent_id') for c in source['chapters'] if c.get('parent_id')}
        leaves = [c for c in source['chapters'] if c['chapter_id'] not in parents]
        topics = [fixture_topic(c) for c in leaves]
        expected = {c['chapter_id'] for c in leaves}
        assert {t['chapter_id'] for t in topics} == expected
        used |= expected
        payload = dict(book_id=book_id, version=2, topics=topics)
        (target / (book_id + '.json')).write_text(json.dumps(payload, ensure_ascii=False, indent=2) + '\n')
        print(f'{book_id}: {len(topics)} lessons, {len(topics)*6} cards, {len(topics)*3} questions')
    assert used == set(BANK), (set(BANK) - used, used - set(BANK))
    print(f'Validated {len(used)} original lessons, {len(used)*4} content blocks, no external calls.')


if __name__ == '__main__':
    main()
